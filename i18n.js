const $ = (s, el = document) => el.querySelector(s);
const $$ = (s, el = document) => [...el.querySelectorAll(s)];

function detectLang() {
  const param = new URLSearchParams(location.search).get("lang");
  if (translations[param]) return param;
  const path = location.pathname.split("/")[1];
  if (translations[path]) return path;
  const saved = localStorage.getItem("lang");
  if (translations[saved]) return saved;
  return (navigator.language || "").startsWith("ar") ? "ar" : "en";
}

function buildMarquee(items) {
  const html = items.map((w) => `<span class="marquee-item">${w}</span>`).join("");
  $("#marquee").innerHTML = html + html + html + html;
}

function applyLang(lang) {
  const t = translations[lang];
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.title = t.name;
  $$("[data-i18n]").forEach((el) => { el.innerHTML = t[el.dataset.i18n]; });
  $$("[data-i18n-html]").forEach((el) => { el.innerHTML = t[el.dataset.i18nHtml]; });
  $$(".lang-switch button").forEach((b) => b.classList.toggle("active", b.dataset.lang === lang));
  buildMarquee(t.marquee);
  localStorage.setItem("lang", lang);
}

let current = detectLang();
applyLang(current);

$$(".lang-switch button").forEach((btn) =>
  btn.addEventListener("click", () => {
    if (btn.dataset.lang === current) return;
    current = btn.dataset.lang;
    document.body.classList.add("switching");
    setTimeout(() => {
      applyLang(current);
      document.body.classList.remove("switching");
    }, 250);
  })
);

// Nav: scrolled state, progress bar, active link
const nav = $("#nav");
const progress = $("#progress");
const sections = $$("main section[id]");
function onScroll() {
  const y = window.scrollY;
  nav.classList.toggle("scrolled", y > 20);
  const max = document.documentElement.scrollHeight - innerHeight;
  progress.style.width = `${(y / max) * 100}%`;
  let active = "";
  sections.forEach((s) => { if (y >= s.offsetTop - 140) active = s.id; });
  $$(".links a").forEach((a) => a.classList.toggle("active", a.getAttribute("href") === `#${active}`));
}
addEventListener("scroll", onScroll, { passive: true });
onScroll();

